import fs from 'node:fs/promises';
const options=JSON.parse(await fs.readFile('/data/options.json','utf8'));
if(!process.env.SUPERVISOR_TOKEN)throw Error('Start Pantry Sync through Home Assistant Apps.');
if(!options.pantry_email||!options.pantry_password)throw Error('Enter your Pantry connector account in the Configuration tab.');
if(!/^todo\.[a-z0-9_]+$/.test(options.list_entity||''))throw Error('Choose a valid to-do entity ID in Configuration.');
process.env.NOTIFICATIONS_ENABLED=options.notifications_enabled?'true':'false';
process.env.HA_URL='http://supervisor';
process.env.HA_API_BASE='http://supervisor/core/api/';
process.env.HA_TOKEN=process.env.SUPERVISOR_TOKEN;
process.env.HA_LIST=options.list_entity;
process.env.PANTRY_EMAIL=options.pantry_email;
process.env.PANTRY_PASSWORD=options.pantry_password;
process.env.PANTRY_HOUSEHOLD=options.household_id||'';
process.env.DATA_DIR='/data/sync';
process.env.SYNC_ENABLED=options.sync_enabled?'true':'false';
await fs.mkdir('/data/sync',{recursive:true});
await fs.chown('/data/sync',1000,1000);
process.setgid(1000);process.setuid(1000);
await import('./bridge.mjs');
